#!/usr/bin/env node
'use strict';
// scripts/build-sdk-bins.cjs — Plan 31-5-9.5 (SDK-06, D-16).
//
// Compile the three TS-entry SDK bins to self-contained CommonJS `.js`
// SIBLINGS so the packed/installed tarball ships RUNNABLE JavaScript. From a
// fresh `npm install`, the SDK entry points live under node_modules; Node
// refuses `--experimental-strip-types` on `.ts` files there
// (ERR_UNSUPPORTED_NODE_MODULES_TYPE_STRIPPING). The dual-mode bin
// trampolines (bin/hone-{sdk,state-mcp,mcp}) prefer the compiled `.js` when it
// exists (installed path) and fall back to the raw `.ts` + strip-types flag
// (in-repo dev). This script produces that `.js`.
//
// WHY esbuild (not tsc): the three entries' transitive import graph crosses
// out of `sdk/` deep into `scripts/lib/**/*.ts` (bidirectionally) and pulls in
// hand-written `.cjs` modules. A `tsc` in-place emit would have to compile and
// ship ~90 `scripts/lib` `.js` siblings (huge tarball churn + a CJS/strip-types
// dual-package hazard) and still depend on every reachable file being runnable
// as plain JS. esbuild bundles each entry into ONE self-contained `.js` with
// every relative `.ts`/`.cjs` dep inlined, leaving only bare packages
// (@modelcontextprotocol/sdk, ajv, node:*) external — exactly 3 new shipped
// files, no scripts/lib churn. The plan (31-5-9.5) authorizes esbuild as the
// fallback when rewriteRelativeImportExtensions hits a runtime edge; the
// cross-boundary `.ts` graph IS that edge.
//
// The emitted `.js` are BUILD ARTIFACTS: gitignored, regenerated by `prepack`
// before every `npm pack`/`npm publish`. The `.ts` remain the source of truth.
//
// Determinism: esbuild output is deterministic for a fixed input + version.
// `--clean` removes prior artifacts first (used by `postpack` / manual tidy).

const esbuild = require('esbuild');
const fs = require('node:fs');
const path = require('node:path');

const REPO_ROOT = path.resolve(__dirname, '..');

// The three TS-entry bins → their compiled sibling. outfile sits NEXT TO the
// source `.ts` so the dual-mode trampoline finds `<dir>/<name>.js`.
const TARGETS = [
  {
    entry: 'sdk/cli/index.ts',
    outfile: 'sdk/cli/index.js',
  },
  {
    entry: 'sdk/mcp/hone-state/server.ts',
    outfile: 'sdk/mcp/hone-state/server.js',
  },
  {
    entry: 'sdk/mcp/hone-mcp/server.ts',
    outfile: 'sdk/mcp/hone-mcp/server.js',
  },
];

function abs(rel) {
  return path.join(REPO_ROOT, rel);
}

function clean() {
  for (const t of TARGETS) {
    const out = abs(t.outfile);
    if (fs.existsSync(out)) fs.rmSync(out, { force: true });
    // esbuild does not emit a .map (sourcemap disabled), but remove a stale one
    // defensively in case a prior config wrote one.
    const map = out + '.map';
    if (fs.existsSync(map)) fs.rmSync(map, { force: true });
  }
}

async function build() {
  for (const t of TARGETS) {
    await esbuild.build({
      entryPoints: [abs(t.entry)],
      outfile: abs(t.outfile),
      bundle: true,
      // CommonJS so the compiled file runs under plain `node <file>` with no
      // package.json "type":"module" dependency and no top-level-await caveats.
      format: 'cjs',
      platform: 'node',
      // Matches package.json engines.node (>=22). The MCP handshake + CLI must
      // run on Node 22/24 across ubuntu/macos/windows CI.
      target: 'node22',
      // Keep bare deps external — they resolve from the installed node_modules
      // (@modelcontextprotocol/sdk, ajv, ...). Bundling them would balloon size
      // and risk duplicate-instance bugs in the MCP SDK.
      packages: 'external',
      // No sourcemap / no minify: these are server/CLI entries, not browser
      // assets; readable stack traces matter more than bytes, and a .map would
      // be an extra untracked artifact to gitignore + ship.
      sourcemap: false,
      minify: false,
      // Preserve the shebang-free CJS shape; the trampoline invokes via
      // `node <file>` so no shebang is needed on the emitted artifact.
      logLevel: 'warning',
    });
  }
}

(async () => {
  const wantClean = process.argv.includes('--clean');
  if (wantClean && !process.argv.includes('--build')) {
    clean();
    return;
  }
  // Always start from a clean slate so a renamed/removed entry never leaves a
  // stale compiled sibling behind.
  clean();
  await build();
})().catch((err) => {
  // eslint-disable-next-line no-console
  console.error('build-sdk-bins: failed:', err && err.message ? err.message : err);
  process.exit(1);
});
